import { lstat, mkdir } from "node:fs/promises";
import { join, posix } from "node:path";
import { notARealFolderRefusal } from "@dohc/workspace-core";
import {
  datasetBaseFolder,
  datasetColumnFields,
  type DatasetColumnField,
  type DatasetDefinition,
  type DatasetRevision,
} from "@dohc/security-contract/dataset";
import { atomicWriteFile } from "../atomicReplaceFile";
import { resolveWorkspaceMetadataDir } from "./workspaceMetadata";

export const DATASET_TYPES_FOLDER = ".dohc/types";

export function datasetTypesPath(
  definition: Pick<DatasetDefinition, "datasetId" | "name" | "schemaPath">,
) {
  const folder = datasetBaseFolder(definition);
  const slug = (folder === "." ? definition.name : folder)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 64)
    .replace(/-+$/g, "");
  return `${DATASET_TYPES_FOLDER}/${slug || "collection"}-${definition.datasetId.toLowerCase()}.d.ts`;
}

const text = (value: string) =>
  JSON.stringify(value)
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
const union = (values: readonly string[], empty: string) =>
  values.length ? values.map(text).join(" | ") : empty;

function valueType(definition: DatasetDefinition, field: DatasetColumnField) {
  const relation = field.relation;
  const target =
    relation &&
    datasetColumnFields(
      definition.tables.find((candidate) => candidate.tableId === relation.tableId)!,
    ).find((candidate) => candidate.fieldId === relation.fieldId)!;
  const type =
    field.type === "number"
      ? "number"
      : field.type === "checkbox"
        ? "boolean"
        : field.type === "select"
          ? union(field.options!, "string")
          : field.type === "multi-select"
            ? `Array<${union(field.options!, "string")}>`
            : target
              ? `${relation.many ? "Array<" : ""}${target.type === "number" ? "number" : "string"}${relation.many ? ">" : ""}`
              : "string";
  return field.required ? type : `${type} | null`;
}

export function datasetTypes({
  revision,
  definition,
}: Pick<DatasetRevision, "revision" | "definition">): string {
  const lines = [
    `// Generated by dohc dataset types from revision ${revision} of ${text(definition.name)}. Run it again after the Collection changes.`,
    "export interface Tables {",
  ];
  for (const table of definition.tables) {
    lines.push(`  ${text(table.sqlName)}: {`);
    for (const field of datasetColumnFields(table))
      lines.push(`    ${text(field.sqlColumn)}: ${valueType(definition, field)};`);
    lines.push("  };");
  }
  lines.push("}", "export interface FieldIds {");
  for (const table of definition.tables) {
    lines.push(`  ${text(table.sqlName)}: {`);
    for (const field of datasetColumnFields(table))
      lines.push(`    ${text(field.sqlColumn)}: ${text(field.fieldId)};`);
    lines.push("  };");
  }
  lines.push("}", "export interface Operations {");
  for (const operation of definition.operations) {
    const table = definition.tables.find((candidate) => candidate.tableId === operation.tableId)!;
    const columns = datasetColumnFields(table)
      .filter((field) => operation.fieldIds.includes(field.fieldId))
      .map((field) => field.sqlColumn);
    lines.push(
      `  ${text(operation.name)}: {`,
      `    kind: ${text(operation.kind)};`,
      `    table: ${text(table.sqlName)};`,
      `    access: ${text(operation.access)};`,
      `    readOnly: ${operation.readOnly};`,
      `    fields: Pick<Tables[${text(table.sqlName)}], ${union(columns, "never")}>;`,
      "  };",
    );
  }
  lines.push(
    "}",
    "export type Row<Table extends keyof Tables> = Tables[Table];",
    "export type OperationName = keyof Operations;",
    "",
  );
  return lines.join("\n");
}

export async function writeDatasetTypes(
  rootPath: string,
  revision: Pick<DatasetRevision, "revision" | "definition">,
): Promise<string> {
  const path = datasetTypesPath(revision.definition);
  const folder = join(await resolveWorkspaceMetadataDir(rootPath), "types");
  await mkdir(folder, { recursive: true });
  const stats = await lstat(folder);
  if (stats.isSymbolicLink() || !stats.isDirectory())
    throw new Error(
      notARealFolderRefusal(
        { path: DATASET_TYPES_FOLDER, lead: "dohc could not write Collection types." },
        stats,
      ),
    );
  await atomicWriteFile(join(folder, posix.basename(path)), datasetTypes(revision));
  return path;
}
