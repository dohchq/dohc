#!/usr/bin/env node
// Shared skills have one canonical body and two native discovery roots.
//
//   skills/<name>/SKILL.md          canonical body, tool-neutral
//   .claude/skills/<name>/SKILL.md  adapter — Claude Code scans this root
//   .agents/skills/<name>/SKILL.md  adapter — Codex CLI scans this root
//
// Every directory under skills/ is a shared skill and gets both adapters. A
// skill that only one host should see lives directly in that host's root with
// no counterpart under skills/ (the codex-* delegation skills work that way:
// Claude runs them, Codex is only the worker they invoke).
//
// Adapters carry the canonical frontmatter verbatim, because the description is
// what makes a host trigger the skill — a stale copy means one tool silently
// stops offering it. `--check` fails when any adapter drifts or is missing.
//
//   node tools/sync-skill-adapters.mjs          rewrite adapters
//   node tools/sync-skill-adapters.mjs --check  verify only, non-zero on drift

import {
  readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync, rmSync, rmdirSync,
} from "node:fs";
import { join, posix } from "node:path";

const CHECK = process.argv.includes("--check");
const SOURCE = "skills";
const ROOTS = [
  { dir: join(".claude", "skills"), host: "Claude Code" },
  { dir: join(".agents", "skills"), host: "Codex CLI" },
];

/** Split a SKILL.md into its raw frontmatter block and the rest. */
function splitFrontmatter(text, file) {
  if (!text.startsWith("---\n") && !text.startsWith("---\r\n")) {
    throw new Error(`${file}: no YAML frontmatter (must start with '---')`);
  }
  const end = text.indexOf("\n---", 3);
  if (end === -1) throw new Error(`${file}: unterminated frontmatter`);
  const close = text.indexOf("\n", end + 1);
  return { frontmatter: text.slice(0, close === -1 ? text.length : close + 1) };
}

// Marks a file as generated. Orphan detection keys off this: a host-only skill
// (the codex-* ones) has no canonical counterpart and must NOT be flagged, so
// "is an adapter" cannot be inferred from location alone.
const MARKER = "<!-- generated by tools/sync-skill-adapters.mjs — do not edit -->";

function adapterFor(frontmatter, canonicalPath, host) {
  const p = posix.join(...canonicalPath.split(/[\\/]/));
  // The closing `---` must end its own line. A canonical file that stops right
  // after it, with no trailing newline, would otherwise produce
  // `---<!-- generated ... -->`, which is not a terminator: the description
  // never parses and the skill silently disappears from both hosts. `--check`
  // could not catch it either, since it compares generated against generated.
  const fm = frontmatter.endsWith("\n") ? frontmatter : `${frontmatter}\n`;
  return `${fm}${MARKER}

# Adapter

${host} discovers skills from this directory, so this file exists to be found.
The skill itself lives in one place:

**[\`${p}\`](${"../".repeat(2)}../${p})**

Read that file and follow it. Do not edit this adapter — run
\`node tools/sync-skill-adapters.mjs\` to regenerate it. \`--check\` fails if it
drifts, goes missing, or outlives the skill it points at.
`;
}

/** Adapter directories in a root whose canonical skill no longer exists. */
function orphansIn(rootDir, canonicalNames) {
  if (!existsSync(rootDir)) return [];
  return readdirSync(rootDir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !canonicalNames.has(e.name))
    .filter((e) => {
      const f = join(rootDir, e.name, "SKILL.md");
      return existsSync(f) && readFileSync(f, "utf8").includes(MARKER);
    })
    .map((e) => join(rootDir, e.name, "SKILL.md"));
}

const shared = readdirSync(SOURCE, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

if (shared.length === 0) {
  console.error(`no shared skills found under ${SOURCE}/`);
  process.exit(1);
}

const problems = [];

// PASS 1 — validate every canonical skill before writing anything. Recording a
// problem and then continuing into the write loop would overwrite two working
// adapters with the invalid frontmatter and only then exit non-zero, so a typo
// in one canonical file would take the skill out of both hosts.
const valid = new Map();
for (const name of shared) {
  const canonical = join(SOURCE, name, "SKILL.md");
  if (!existsSync(canonical)) {
    problems.push(`${SOURCE}/${name}/ has no SKILL.md — create it, or remove the directory`);
    continue;
  }
  let frontmatter;
  try {
    ({ frontmatter } = splitFrontmatter(readFileSync(canonical, "utf8"), canonical));
  } catch (err) {
    problems.push(err.message);
    continue;
  }
  let ok = true;
  // A host triggers a skill off its description, so an adapter without one is
  // discovered and never used.
  for (const key of ["name", "description"]) {
    if (!new RegExp(`^${key}:`, "m").test(frontmatter)) {
      problems.push(`${canonical} frontmatter has no '${key}:'`);
      ok = false;
    }
  }
  if (!new RegExp(`^name:[ \\t]*${name}[ \\t]*$`, "m").test(frontmatter)) {
    problems.push(`${canonical} frontmatter 'name:' does not match its directory (${name})`);
    ok = false;
  }
  if (ok) valid.set(name, frontmatter);
}

if (problems.length > 0) {
  console.error(`canonical skills are invalid (${problems.length}) — wrote nothing:`);
  for (const p of problems) console.error(`  ${p}`);
  process.exit(1);
}
let wrote = 0;

// PASS 2 — every canonical skill is known good, so writing is safe.
for (const [name, frontmatter] of valid) {
  const canonical = join(SOURCE, name, "SKILL.md");

  for (const { dir, host } of ROOTS) {
    const target = join(dir, name, "SKILL.md");
    const want = adapterFor(frontmatter, canonical, host);
    const have = existsSync(target) ? readFileSync(target, "utf8") : null;

    if (have === want) continue;

    if (CHECK) {
      problems.push(have === null ? `MISSING  ${target}` : `DRIFTED  ${target}`);
      continue;
    }
    mkdirSync(join(dir, name), { recursive: true });
    writeFileSync(target, want, "utf8");
    console.log(`${have === null ? "created" : "updated"}  ${target}`);
    wrote++;
  }
}

// An adapter that outlives its canonical skill keeps advertising a description
// to both hosts while its link points at a deleted file. Iterating only skills/
// can never see that, so scan the roots too.
const canonicalNames = new Set(shared);
for (const { dir } of ROOTS) {
  for (const orphan of orphansIn(dir, canonicalNames)) {
    if (CHECK) {
      problems.push(`ORPHANED ${orphan} — no matching ${SOURCE}/<name>/SKILL.md`);
      continue;
    }
    // Delete the adapter file, then the directory only if nothing else is left.
    // A recursive delete here would take human-written siblings with it, and it
    // turns "copied an adapter as a template" into silent data loss.
    rmSync(orphan, { force: true });
    const dir = join(orphan, "..");
    if (readdirSync(dir).length === 0) rmdirSync(dir);
    console.log(`removed  ${orphan} (canonical skill is gone)`);
    wrote++;
  }
}

if (problems.length > 0) {
  console.error(`\nskill adapters out of sync (${problems.length}):`);
  for (const p of problems) console.error(`  ${p}`);
  console.error(`\nrun: node tools/sync-skill-adapters.mjs`);
  process.exit(1);
}

console.log(
  CHECK
    ? `skill adapters OK — ${shared.length} shared skill(s) x ${ROOTS.length} roots`
    : wrote === 0
      ? `already in sync — ${shared.length} shared skill(s)`
      : `synced ${wrote} adapter file(s)`,
);
